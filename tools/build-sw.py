#!/usr/bin/env python3
"""Regenerate sw.js with a cache version derived from the app files.
Run after changing any app file:  python3 tools/build-sw.py"""
import os, hashlib
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
core = ['./', 'index.html', 'style.css', 'fonts.css', 'app.js', 'manifest.webmanifest', 'vendor/JsBarcode.all.min.js', 'vendor/qrcode.js',
        'data/label-db.js', 'data/icons.js', 'icons/icon-192.png', 'icons/icon-512.png']
core += ['fonts/' + f for f in sorted(os.listdir('fonts')) if f.endswith('.woff2')]
lazy = ['vendor/html2canvas.min.js', 'vendor/jspdf.umd.min.js', 'vendor/xlsx.mini.min.js', 'vendor/bwip-js-min.js']
h = hashlib.sha1()
for f in core[1:] + lazy:
    h.update(open(f, 'rb').read())
ver = h.hexdigest()[:10]
core_js = '[\n' + ''.join(f"  '{c}',\n" for c in core) + ']'
sw = f"""/* Service worker (generated by tools/build-sw.py): makes the app work offline and installable.
 * Core files are cached on install; large libraries are cached the first time they are used. */
const CACHE = 'sticker-creator-{ver}';
const CORE = {core_js};

self.addEventListener('install', (e) => {{
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(CORE)).then(() => self.skipWaiting()));
}});
self.addEventListener('activate', (e) => {{
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
}});
self.addEventListener('fetch', (e) => {{
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  // Network-first for the page so updates arrive quickly; cache-first for everything else.
  if (req.mode === 'navigate') {{
    e.respondWith(fetch(req).then((res) => {{ const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); return res; }})
      .catch(() => caches.match(req, {{ ignoreSearch: true }}).then((r) => r || caches.match('index.html'))));
    return;
  }}
  e.respondWith(caches.match(req, {{ ignoreSearch: true }}).then((hit) => hit || fetch(req).then((res) => {{
    if (res.ok) {{ const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }}
    return res;
  }})));
}});
"""
open('sw.js', 'w').write(sw)
print('sw.js cache version', ver)
